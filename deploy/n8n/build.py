RESPONSE_LIMIT = 12 * 1024 * 1024  # bytes returned to jarvis-control

VALIDATE = """\
// Generated by build.py. Rejects anything outside this account's read-only list.
const policy = __POLICY__;
const request = ($input.first().json.body) || {};
const fail = (message) => { throw new Error('jarvis_policy: ' + message); };
if (typeof request !== 'object' || Array.isArray(request)) fail('body');
const extra = Object.keys(request).filter((k) => !['method', 'path', 'query', 'headers', 'body'].includes(k));
if (extra.length) fail('fields');
const method = request.method;
const path = request.path;
if (typeof method !== 'string' || typeof path !== 'string') fail('route');
if (/\\.\\.|%2f|%5c|%00/i.test(path)) fail('path');
if (!policy.routes.some(([m, p]) => m === method && new RegExp('^' + p + '$').test(path))) fail('route');
// The task runner sandbox has no URLSearchParams.
const params = [];
const query = request.query || {};
if (typeof query !== 'object' || Array.isArray(query)) fail('query');
for (const [key, value] of Object.entries(query)) {
  if (!/^[$A-Za-z0-9_.]{1,40}$/.test(key)) fail('query key');
  for (const v of Array.isArray(value) ? value : [value]) {
    if (!['string', 'number', 'boolean'].includes(typeof v) || String(v).length > 2000) fail('query value');
    params.push(encodeURIComponent(key) + '=' + encodeURIComponent(String(v)));
  }
}
const headers = { ...policy.fixed_headers };
for (const [key, value] of Object.entries(request.headers || {})) {
  const pattern = policy.headers[key];
  if (!pattern || typeof value !== 'string' || !new RegExp('^' + pattern + '$').test(value)) fail('header');
  headers[key] = value;
}
let body = request.body;
if (method === 'GET' && body !== undefined) fail('body on GET');
if (method === 'POST') {
  if (typeof body !== 'object' || body === null || Array.isArray(body)) fail('body');
  if (JSON.stringify(body).length > 8000) fail('body size');
}
const qs = params.join('&');
return [{ json: {
  method,
  url: policy.host + path + (qs ? '?' + qs : ''),
  headers,
  body: method === 'POST' ? JSON.stringify(body) : '',
} }];
"""

PACK = """\
// Generated by build.py. Provider status and body, never the credential.
const item = $input.first();
const limit = __LIMIT__;
// The node's error reaches here without details (an empty object): a failed
// token refresh and a network failure look the same, so report status 0.
if (item.json.statusCode === undefined) {
  return [{ json: { status: 0, error: 'provider_unreachable_or_unauthorized' } }];
}
let buffer = Buffer.alloc(0);
if (item.binary && item.binary.data) {
  buffer = await this.helpers.getBinaryDataBuffer(0, 'data');
}
const headers = item.json.headers || {};
return [{ json: {
  status: item.json.statusCode,
  content_type: String(headers['content-type'] || ''),
  truncated: buffer.length > limit,
  body_base64: buffer.subarray(0, limit).toString('base64'),
} }];
"""


def policy(provider: str) -> dict:
    spec = PROVIDERS[provider]
    return {
        "host": spec["host"],
        "routes": [[m, p] for m, p in spec["routes"]],
        "headers": spec["headers"],
        "fixed_headers": spec["fixed_headers"],
    }


def auth_parameters(provider: str) -> tuple[dict, str]:
    if provider == "notion":
        return {
            "authentication": "predefinedCredentialType",
            "nodeCredentialType": "notionApi",
        }, "notionApi"
    return {
        "authentication": "genericCredentialType",
        "genericAuthType": "oAuth2Api",
    }, "oAuth2Api"


def workflow(account: str) -> dict:
    spec = ACCOUNTS[account]
    provider = spec["provider"]
    auth, credential_type = auth_parameters(provider)
    slug = account.replace("_", "-")
    nodes = [
        {
            "id": f"{slug}-webhook",
            "name": "Gateway",
            "type": "n8n-nodes-base.webhook",
            "typeVersion": 2,
            "position": [0, 0],
            "webhookId": f"jarvis-{slug}",
            "parameters": {
                "httpMethod": "POST",
                "path": f"jarvis-{slug}",
                "authentication": "headerAuth",
                "responseMode": "responseNode",
                "options": {},
            },
            "credentials": {"httpHeaderAuth": GATEWAY_CREDENTIAL},
        },
        {
            "id": f"{slug}-validate",
            "name": "Validate",
            "type": "n8n-nodes-base.code",
            "typeVersion": 2,
            "position": [220, 0],
            "parameters": {
                "jsCode": VALIDATE.replace(
                    "__POLICY__", json.dumps(policy(provider), indent=2)
                )
            },
        },
        {
            "id": f"{slug}-request",
            "name": "Provider",
            "type": "n8n-nodes-base.httpRequest",
            "typeVersion": 4.2,
            "position": [440, 0],
            "onError": "continueRegularOutput",
            "parameters": {
                "method": "={{ $json.method }}",
                "url": "={{ $json.url }}",
                **auth,
                "sendHeaders": True,
                "specifyHeaders": "json",
                "jsonHeaders": "={{ JSON.stringify($json.headers) }}",
                "sendBody": "={{ $json.method === 'POST' }}",
                "contentType": "raw",
                "rawContentType": "application/json",
                "body": "={{ $json.body }}",
                "options": {
                    "response": {
                        "response": {
                            "fullResponse": True,
                            "neverError": True,
                            "responseFormat": "file",
                        }
                    },
                    "timeout": 25000,
                },
            },
            "credentials": {credential_type: spec["credential"]},
        },
        {
            "id": f"{slug}-pack",
            "name": "Pack",
            "type": "n8n-nodes-base.code",
            "typeVersion": 2,
            "position": [660, 0],
            "parameters": {"jsCode": PACK.replace("__LIMIT__", str(RESPONSE_LIMIT))},
        },
        {
            "id": f"{slug}-respond",
            "name": "Respond",
            "type": "n8n-nodes-base.respondToWebhook",
            "typeVersion": 1.1,
            "position": [880, 0],
            "parameters": {"respondWith": "firstIncomingItem", "options": {}},
        },
    ]
    order = [node["name"] for node in nodes]
    return {
        "id": f"jarvisPx{account.replace('_', '').title()}"[:16].ljust(16, "0"),
        "name": f"Jarvis proxy {account}",
        "active": False,
        "nodes": nodes,
        "connections": {
            a: {"main": [[{"node": b, "type": "main", "index": 0}]]}
            for a, b in zip(order, order[1:])
        },
        "settings": {
            "executionOrder": "v1",
            "saveDataErrorExecution": "none",
            "saveDataSuccessExecution": "none",
            "saveManualExecutions": False,
            "saveExecutionProgress": False,
            "executionTimeout": 60,
        },
        "pinData": {},
        "tags": [],
    }


def credentials() -> list[dict]:
    """Skeletons: the user adds client ID/secret and signs in from the n8n UI."""
    items = [
        {
            **GATEWAY_CREDENTIAL,
            "type": "httpHeaderAuth",
            "data": {"name": "X-Jarvis-Gateway", "value": "__GATEWAY_SECRET__"},
        }
    ]
    for spec in ACCOUNTS.values():
        if spec["provider"] == "google":
            scopes = ["openid", "email"] + [GOOGLE_SCOPES[s] for s in spec["services"]]
            data = {
                "grantType": "authorizationCode",
                "authUrl": "https://accounts.google.com/o/oauth2/v2/auth",
                "accessTokenUrl": "https://oauth2.googleapis.com/token",
                "clientId": "",
                "clientSecret": "",
                "scope": " ".join(scopes),
                "authQueryParameters": "access_type=offline&prompt=consent",
                "authentication": "body",
            }
            kind = "oAuth2Api"
        elif spec["provider"] == "microsoft":
            base = "https://login.microsoftonline.com/common/oauth2/v2.0"
            data = {
                "grantType": "authorizationCode",
                "authUrl": f"{base}/authorize",
                "accessTokenUrl": f"{base}/token",
                "clientId": "",
                "clientSecret": "",
                "scope": "openid email offline_access User.Read Mail.Read",
                "authQueryParameters": "prompt=select_account",
                "authentication": "body",
            }
            kind = "oAuth2Api"
        else:
            data, kind = {"apiKey": ""}, "notionApi"
        items.append({**spec["credential"], "type": kind, "data": data})
    return items


def main() -> None:
    out = HERE / "workflows"
    out.mkdir(exist_ok=True)
    for account in ACCOUNTS:
        path = out / f"{account}.json"
        path.write_text(
            json.dumps(workflow(account), indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8",
        )
    (HERE / "credentials.template.json").write_text(
        json.dumps(credentials(), indent=2) + "\n", encoding="utf-8"
    )
    print(f"wrote {len(ACCOUNTS)} workflows and credentials.template.json")


if __name__ == "__main__":
    main()
