ID = r"[A-Za-z0-9_-]{1,200}"
# Percent-encoded single path segment (calendar IDs are e-mail-like, with # as %23).
SEGMENT = r"[A-Za-z0-9%._~@+-]{1,300}"
NOTION_ID = r"[0-9a-f]{8}-?[0-9a-f]{4}-?[0-9a-f]{4}-?[0-9a-f]{4}-?[0-9a-f]{12}"

